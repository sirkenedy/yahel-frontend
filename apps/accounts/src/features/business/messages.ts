/** The locale the flow is written in. Money, dates, month names and country names follow it. */
const locale = 'en-NG';
const day = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
const whole = new Map<string, Intl.NumberFormat>();
const moneyFormat = (currency: string, fraction: boolean) => {
  const key = `${currency}${fraction}`;
  const known = whole.get(key) ?? new Intl.NumberFormat(locale, { style: 'currency', currency, minimumFractionDigits: fraction ? 2 : 0, maximumFractionDigits: fraction ? 2 : 0 });
  whole.set(key, known);
  return known;
};
/** An amount for the person, in its own currency, without ".00" on a whole amount. Amounts arrive in the currency's smallest unit. */
const money = ({ amount, currency }: Money) => moneyFormat(currency, amount % 100 !== 0).format(amount / 100);
const people = (count: number) => `${count} ${count === 1 ? 'person' : 'people'}`;
const amountPer = (charge: Pick<ScheduledCharge, 'amount' | 'per'>) => `${money(charge.amount)}${charge.per ? ` / ${charge.per}` : ''}`;

