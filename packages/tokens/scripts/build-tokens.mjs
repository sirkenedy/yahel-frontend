#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (name) => JSON.parse(readFileSync(join(root, 'tokens', name), 'utf8'));

const flatten = (node, path = [], out = {}) => {
  for (const [key, value] of Object.entries(node)) {
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) flatten(value, [...path, key], out);
    else out[[...path, key].join('.')] = value;
  }
  return out;
};

const primitives = flatten(load('primitive.json'));
const resolve = (value) =>
  String(value).replace(/\{([^}]+)\}/g, (_, ref) => {
    if (!(ref in primitives)) throw new Error(`Unknown token reference {${ref}}`);
    return primitives[ref];
  });
const resolved = (file) => Object.fromEntries(Object.entries(flatten(load(file))).map(([k, v]) => [k, resolve(v)]));

const light = resolved('semantic.light.json');
const dark = resolved('semantic.dark.json');
const lightHc = resolved('semantic.light.hc.json');
const darkHc = resolved('semantic.dark.hc.json');
const chart = flatten(load('chart.json').chart);
const chartFor = (theme) => Object.fromEntries(Object.entries(chart).filter(([k]) => k.startsWith(`${theme}.`)).map(([k, v]) => [`chart.${k.slice(theme.length + 1)}`, v]));
const apps = resolved('apps.json');
const errors = [];

errors.push(
  ...Object.keys(light).filter((k) => !(k in dark)).map((k) => `${k} has no dark value`),
  ...Object.keys(dark).filter((k) => !(k in light)).map((k) => `${k} has no light value`),
  ...Object.keys(lightHc).filter((k) => !(k in light)).map((k) => `light increased-contrast override ${k} is not a semantic token`),
  ...Object.keys(darkHc).filter((k) => !(k in dark)).map((k) => `dark increased-contrast override ${k} is not a semantic token`),
  ...Object.keys(lightHc).filter((k) => !(k in darkHc)).map((k) => `${k} has a light increased-contrast override but no dark one`),
  ...Object.keys(darkHc).filter((k) => !(k in lightHc)).map((k) => `${k} has a dark increased-contrast override but no light one`),
);

const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
// Increased contrast raises AA thresholds to AAA: 4.5 → 7 for text, 3 → 4.5 for borders.
const raised = (min) => (min >= 4.5 ? 7 : 4.5);
const themes = [
  ['light', light, (min) => min],
  ['dark', dark, (min) => min],
  ['light increased-contrast', { ...light, ...lightHc }, raised],
  ['dark increased-contrast', { ...dark, ...darkHc }, raised],
];
const { pairs } = load('contrast-pairs.json');
for (const [theme, tokens, threshold] of themes) {
  for (const [fg, bg, min] of pairs) {
    const [f, b] = [tokens[fg], tokens[bg]];
    if (!/^#[0-9a-f]{6}$/i.test(f ?? '') || !/^#[0-9a-f]{6}$/i.test(b ?? '')) {
      errors.push(`${theme}: ${fg} on ${bg} must both be opaque hex colours to be checked`);
      continue;
    }
    const actual = ratio(f, b);
    if (actual < threshold(min)) errors.push(`${theme}: ${fg} on ${bg} is ${actual.toFixed(2)}:1, needs ${threshold(min)}:1`);
  }
}

for (const [name, hex] of Object.entries(apps)) {
  const min = name.startsWith('avatar.') ? 4.5 : 3;
  const actual = ratio('#FFFFFF', hex);
  if (actual < min) errors.push(`${name}: white on ${hex} is ${actual.toFixed(2)}:1, needs ${min}:1`);
}

if (errors.length) {
  console.error(`Token check failed:\n- ${errors.join('\n- ')}`);
  process.exit(1);
}

const vars = (tokens, indent = '  ') =>
  Object.entries(tokens)
    .map(([k, v]) => `${indent}--ws-${k.replaceAll('.', '-')}: ${v};`)
    .join('\n');

const rem = (px) => `${px / 16}rem`;
const { roles } = load('type.json');
const typeVars = (sizeClass, indent = '  ') =>
  Object.entries(roles)
    .map(([role, r]) => `${indent}--ws-type-${role}-size: ${rem(r[sizeClass][0])};\n${indent}--ws-type-${role}-line: ${rem(r[sizeClass][1])};`)
    .join('\n');
const typeStatics = Object.entries(roles)
  .map(([role, r]) => `  --ws-type-${role}-weight: ${r.weight};\n  --ws-type-${role}-weight-emphasized: ${r.emphasized};\n  --ws-type-${role}-tracking: ${r.tracking};`)
  .join('\n');

const css = `/* Generated by packages/tokens/scripts/build-tokens.mjs. Do not edit; change tokens/*.json and rebuild. */
:root {
${vars(primitives)}
${vars(flatten(load('scale.json')))}
${vars(apps)}
${typeStatics}
${typeVars('touch')}
${vars(light)}
${vars(chartFor('light'))}
  color-scheme: light dark;
}

@media (hover: hover) and (pointer: fine) {
  :root {
${typeVars('pointer', '    ')}
  }
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(dark, '    ')}
${vars(chartFor('dark'), '    ')}
  }
}

:root[data-theme='dark'] {
${vars(dark)}
${vars(chartFor('dark'))}
}

@media (prefers-contrast: more) {
  :root {
${vars(lightHc, '    ')}
  }
}

@media (prefers-contrast: more) and (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(darkHc, '    ')}
  }
}

@media (prefers-contrast: more) {
  :root[data-theme='dark'] {
${vars(darkHc, '    ')}
  }
}

:root[data-contrast='more'] {
${vars(lightHc)}
}

:root[data-contrast='more'][data-theme='dark'] {
${vars(darkHc)}
}
`;

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'tokens.css'), css);
const scale = flatten(load('scale.json'));
writeFileSync(
  join(root, 'dist', 'tokens.json'),
  `${JSON.stringify({ primitive: primitives, scale, type: roles, app: apps, themes: { light: { ...light, ...chartFor('light') }, dark: { ...dark, ...chartFor('dark') }, 'light-increased-contrast': lightHc, 'dark-increased-contrast': darkHc } }, null, 2)}\n`,
);
console.log(`Tokens OK: ${Object.keys(light).length} semantic tokens per theme, ${pairs.length} contrast pairs pass in 4 themes. Wrote dist/tokens.css and dist/tokens.json`);
